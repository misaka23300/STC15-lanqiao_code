void LIN_ISR_Handler ( void ) interrupt LIN_VECTOR
{
	u8 isr;
	u8 arTemp;
	arTemp = LINAR;     //LINAR ֳ棬ѭд LINAR жϣж޸ LINAR 
	
	isr = LinReadReg( LSR );		//ȡĴ״̬־λ
	if (( isr & 0x03 ) == 0x03 )
	{
		isr = LinReadReg( LER );
		if ( isr == 0x00 )		//No Error
		{
			LinRxFlag = 1;
		}
	}
	else
	{
		isr = LinReadReg( LER );	//ȡĴ
	}

	LINAR = arTemp;    //LINAR ֳָ
}

